let currentLang = localStorage.getItem(STORAGE_KEY) || "en";
const renderCallbacks = [];

export function t(key, ...args) {
  const entry = dict[currentLang]?.[key] ?? dict.en[key];
  if (typeof entry === "function") return entry(...args);
  return entry ?? key;
}

export function getLang() {
  return currentLang;
}

export function isArabic() {
  return currentLang === "ar";
}

export function onLanguageChange(callback) {
  renderCallbacks.push(callback);
}

function applyDomLanguage() {
  document.documentElement.lang = currentLang;
  document.body.classList.toggle("lang-ar", currentLang === "ar");
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    el.textContent = t(key);
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const key = el.dataset.i18nHtml;
    el.innerHTML = t(key);
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nAria));
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  const langBtn = document.getElementById("lang-btn");
  if (langBtn) langBtn.textContent = currentLang === "en" ? "عربي" : "EN";
}

export function setLang(lang) {
  currentLang = lang === "ar" ? "ar" : "en";
  try {
    localStorage.setItem(STORAGE_KEY, currentLang);
  } catch {
    /* private browsing */
  }
  applyDomLanguage();
  for (const cb of renderCallbacks) cb();
}

export function initI18n() {
  applyDomLanguage();
  const langBtn = document.getElementById("lang-btn");
  langBtn?.addEventListener("click", () => setLang(currentLang === "en" ? "ar" : "en"));
}
